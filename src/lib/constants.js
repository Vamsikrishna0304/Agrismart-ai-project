import { getLang, tr } from "@/lib/i18n";

function locale() {
  return getLang() === "te" ? "te-IN" : undefined;
}

export function formatDate(value) {
  if (!value) return "—";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "—";
  return date.toLocaleDateString(locale(), { day: "numeric", month: "short", year: "numeric" });
}

export function formatDateTime(value) {
  if (!value) return "—";
  const date = new Date(value);
  if (Number.isNaN(date.getTime())) return "—";
  return date.toLocaleString(locale(), { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" });
}

/**
 * Freshness band for a reading age, using the same limits the irrigation engine and
 * the device staleness check apply, so the dashboard never calls a value current
 * when the rest of the app is treating it as stale.
 */
export function freshnessState(minutes) {
  if (minutes === null || minutes === undefined) return "stale";
  if (minutes <= 120) return "fresh";
  if (minutes <= 360) return "aging";
  return "stale";
}

export function freshnessLabel(minutes) {
  if (minutes === null || minutes === undefined) return tr("age unknown");
  if (minutes < 60) return tr("{minutes} min old", { minutes });
  const hours = Math.round(minutes / 60);
  if (hours < 48) return tr("{hours} h old", { hours });
  return tr("{days} d old", { days: Math.round(hours / 24) });
}
