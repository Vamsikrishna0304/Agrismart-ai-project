import React from "react";
import { BrainCircuit, Calculator, Ruler, Waves } from "lucide-react";
import { useI18n } from "@/lib/i18n";

const KINDS = {
  measured: {
    label: "Measured",
    Icon: Ruler,
    classes: "bg-sky-50 text-sky-800 border-sky-200",
    note: "A value someone actually measured or recorded.",
  },
  modelled: {
    label: "Model output",
    Icon: BrainCircuit,
    classes: "bg-violet-50 text-violet-800 border-violet-200",
    note: "Produced by a model from your inputs. It is an estimate, never a measurement.",
  },
  rule: {
    label: "Rule engine",
    Icon: Calculator,
    classes: "bg-emerald-50 text-emerald-800 border-emerald-200",
    note: "Produced by transparent threshold rules, not machine learning.",
  },
  simulated: {
    label: "Simulated",
    Icon: Waves,
    classes: "bg-amber-50 text-amber-900 border-amber-200",
    note: "Demo data generated by the simulator. Not a physical sensor reading.",
  },
};

export default function ProvenanceBadge({ kind = "measured", label, note, className = "" }) {
  const meta = KINDS[kind] || KINDS.measured;
  const { t } = useI18n();
  const { Icon } = meta;
  return (
    <span
      title={t(note || meta.note)}
      className={`inline-flex items-center gap-1 whitespace-nowrap rounded-full border px-2.5 py-0.5 text-xs font-medium ${meta.classes} ${className}`}
    >
      <Icon className="h-3.5 w-3.5" />
      {t(label || meta.label)}
    </span>
  );
}
